panel = []
def add(df, group, indicator, unit, source, note=''):
    df = df[['oktmo', 'year', 'value']].dropna(subset=['value']).copy()
    df['oktmo'] = df['oktmo'].astype(str)
    df = df[df.oktmo.isin(OK2MO)]
    dup = df.duplicated(['oktmo', 'year']).sum()
    if dup:
        log.append(f'ДУБЛИ {indicator}: {dup} — взято первое значение')
        df = df.drop_duplicates(['oktmo', 'year'])
    df['year'] = df['year'].astype(int)
    df['mo'] = df.oktmo.map(OK2MO)
    df['group'], df['indicator'], df['unit'], df['source'], df['note'] = group, indicator, unit, source, note
    panel.append(df)
    log.append(f'{indicator}: {len(df)} наблюдений, {df.year.min()}–{df.year.max()}, МО: {df.oktmo.nunique()}')

